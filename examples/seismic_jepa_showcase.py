class SeismicStressEmbeddingNode(BaseNode):
    """
    Encodes raw per-station waveform features into the latent stress field.

    Reads  : state["stress_data"]         (B, N_STATIONS, 6)
    Writes : state["stress_embedding"]    (B, STRESS_DIM)
             state["event_index"]         int
    """
    def __init__(self, jepa: SeismicStressJEPA, next_node=None):
        self.jepa      = jepa
        self.next_node = next_node

    def execute(self, state: GraphState):
        stress_data = state.get("stress_data")   # (B, N_STATIONS, 6)
        with torch.no_grad():
            z_stress = self.jepa.encode_stress_field(stress_data)  # (B, STRESS_DIM)

        state.set("stress_embedding", z_stress)
        idx = state.get("event_index", 0)
        print(f"\n[SeismicStressEmbeddingNode] Event {idx}: "
              f"stress field encoded → Z_s shape {list(z_stress.shape)}, "
              f"mean={z_stress.mean().item():.4f}")
        return self.next_node


class FaultTopologyEmbeddingNode(BaseNode):
    """
    Encodes the geological fault network topology into the structural sequence.

    Reads  : state["fault_topology"]      (1, N_FAULT_SEGS, 6)
    Writes : state["fault_embedding"]     (1, N_FAULT_SEGS, FAULT_DIM)
    """
    def __init__(self, jepa: GeologicalFaultJEPA, next_node=None):
        self.jepa      = jepa
        self.next_node = next_node

    def execute(self, state: GraphState):
        fault_topology = state.get("fault_topology")   # (1, N_FAULT_SEGS, 6)
        with torch.no_grad():
            z_fault = self.jepa(fault_topology)        # (1, N_FAULT_SEGS, FAULT_DIM)

        state.set("fault_embedding", z_fault)
        print(f"\n[FaultTopologyEmbeddingNode] Fault network encoded → "
              f"Z_f shape {list(z_fault.shape)}, "
              f"mean={z_fault.mean().item():.4f}")
        return self.next_node


class TectonicRiskHeadNode(BaseNode):
    """
    Applies cross-attention to project the crustal stress field against the
    fault topology, producing a tectonic risk score and topk high-risk segments.

    Reads  : state["stress_embedding"]   (B, STRESS_DIM)
             state["fault_embedding"]    (1, N_FAULT_SEGS, FAULT_DIM)
    Writes : state["risk_score"]         float in [0, 1]
             state["risk_coords"]        list of (label, segment_index) tuples
             state["attn_weights"]       (B, N_FAULT_SEGS)
    """
    def __init__(self, head: TectonicRiskHead, k: int = 3, next_node=None):
        self.head      = head
        self.k         = k
        self.next_node = next_node

    def execute(self, state: GraphState):
        z_stress = state.get("stress_embedding")   # (B, STRESS_DIM)
        z_fault  = state.get("fault_embedding")    # (1, N_FAULT_SEGS, FAULT_DIM)

        with torch.no_grad():
            risk_score, attn_weights = self.head(z_stress, z_fault)

        risk_val    = risk_score.mean().item()
        risk_coords = self.head.topk_fault_segments(attn_weights, k=self.k)

        state.set("risk_score",   risk_val)
        state.set("risk_coords",  risk_coords)
        state.set("attn_weights", attn_weights)

        print(f"\n[TectonicRiskHeadNode]  aggregate risk = {risk_val:.4f}")
        print(f"  topk fault segments (k={self.k}):")
        for label, idx in risk_coords:
            w = attn_weights.mean(0)[idx].item()
            print(f"    [{idx:>2}] {label:<45} attn={w:.4f}")
        return self.next_node


class RiskThresholdRouterNode(BaseNode):
    """
    Routes on tectonic risk magnitude.

    HIGH risk (risk_score >= threshold) → high_risk_node
    LOW  risk                           → low_risk_node
    """
    def __init__(
        self,
        threshold: float = 0.55,
        high_risk_node=None,
        low_risk_node=None,
    ):
        self.threshold      = threshold
        self.high_risk_node = high_risk_node
        self.low_risk_node  = low_risk_node

    def execute(self, state: GraphState):
        risk = state.get("risk_score", 0.0)
        tier = "HIGH" if risk >= self.threshold else "LOW"
        state.set("risk_tier", tier)
        print(f"\n[RiskThresholdRouterNode]  risk={risk:.4f}  threshold={self.threshold}  → {tier}")
        return self.high_risk_node if risk >= self.threshold else self.low_risk_node


class RiskReportNode(BaseNode):
    """
    Generates a structured seismic risk assessment report.
    Writes final report to state and prints to console.
    """
    def __init__(self, next_node=None):
        self.next_node = next_node

    def execute(self, state: GraphState):
        risk_score  = state.get("risk_score", 0.0)
        risk_coords = state.get("risk_coords", [])
        event_idx   = state.get("event_index", 0)

        report = {
            "event_index":      event_idx,
            "risk_tier":        "HIGH",
            "aggregate_risk":   round(risk_score, 4),
            "critical_segments": [
                {"label": label, "segment_id": idx}
                for label, idx in risk_coords
            ],
            "recommendation":   "Escalate to seismic monitoring authority. "
                                 "Increase station sampling rate on critical segments. "
                                 "Review infrastructure exposure on identified coordinates.",
        }
        state.set("risk_report", report)

        print("\n" + "=" * 60)
        print("  TECTONIC RISK REPORT — HIGH ALERT")
        print("=" * 60)
        print(f"  Event:            {event_idx}")
        print(f"  Aggregate Risk:   {risk_score:.4f}")
        print(f"  Critical Segments:")
        for seg in report["critical_segments"]:
            print(f"    • [{seg['segment_id']:>2}] {seg['label']}")
        print(f"  Recommendation:   {report['recommendation']}")
        print("=" * 60)
        return self.next_node


class LogLowRiskNode(BaseNode):
    """Logs a low-risk monitoring event for background tracking."""
    def __init__(self, next_node=None):
        self.next_node = next_node

    def execute(self, state: GraphState):
        risk  = state.get("risk_score", 0.0)
        idx   = state.get("event_index", 0)
        print(f"\n[LogLowRiskNode] Event {idx}: risk={risk:.4f} — below threshold. Logged for background monitoring.")
        state.set("risk_report", {"event_index": idx, "risk_tier": "LOW", "aggregate_risk": round(risk, 4)})
        return self.next_node


# ---------------------------------------------------------------------------
# Graph Assembly
# ---------------------------------------------------------------------------

def build_seismic_graph():
    """
    Assembles and returns the Lár seismic risk graph.

    Nodes are instantiated with global model instances.
    The graph is deterministic: same inputs produce identical outputs.
    """
    # Terminal nodes
    report_node   = RiskReportNode(next_node=None)
    log_node      = LogLowRiskNode(next_node=None)

    # Risk router — threshold calibrated for synthetic uniform-random data
    router_node = RiskThresholdRouterNode(
        threshold=0.50,
        high_risk_node=report_node,
        low_risk_node=log_node,
    )

    # TectonicRiskHead: cross-attention, topk=3 fault segments
    risk_head_node = TectonicRiskHeadNode(
        head=_risk_head,
        k=3,
        next_node=router_node,
    )

    # Fault topology embedding — computed once, shared across events
    fault_emb_node = FaultTopologyEmbeddingNode(
        jepa=_fault_jepa,
        next_node=risk_head_node,
    )

    # Seismic stress embedding — computed per event
    stress_emb_node = SeismicStressEmbeddingNode(
        jepa=_stress_jepa,
        next_node=fault_emb_node,
    )

    return stress_emb_node   # entry point


