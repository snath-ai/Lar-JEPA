# ---------------------------------------------------------------------------
# SeismicStressJEPA — encodes crustal stress observations into latent space
# ---------------------------------------------------------------------------

class SeismicStressJEPA(nn.Module):
    """
    JEPA encoder for the seismic stress field (environmental state).

    Input  : (B, N_STATIONS, 6) — per-station waveform feature vectors
    Output : (B, N_STATIONS, STRESS_DIM) — per-station latent stress embeddings

    The encoder learns which combinations of station observations (ground
    motion, frequency content, P/S ratios) are predictive of the underlying
    crustal stress state — the "world model" representation of the stress field.
    """
    def __init__(self, in_features: int = 6, embed_dim: int = STRESS_DIM):
        super().__init__()
        self.station_encoder = nn.Sequential(
            nn.Linear(in_features, 128),
            nn.LayerNorm(128),
            nn.GELU(),
            nn.Linear(128, embed_dim),
        )
        self.spatial_attention = nn.MultiheadAttention(
            embed_dim=embed_dim, num_heads=4, batch_first=True
        )
        self.norm = nn.LayerNorm(embed_dim)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        z = self.station_encoder(x)               # (B, N_STATIONS, STRESS_DIM)
        z_attn, _ = self.spatial_attention(z, z, z)
        return self.norm(z + z_attn)              # (B, N_STATIONS, STRESS_DIM)

    def encode_stress_field(self, x: torch.Tensor) -> torch.Tensor:
        """Returns mean-pooled stress field embedding: (B, STRESS_DIM)."""
        station_embs = self.forward(x)            # (B, N_STATIONS, STRESS_DIM)
        return station_embs.mean(dim=1)           # (B, STRESS_DIM)


# ---------------------------------------------------------------------------
# GeologicalFaultJEPA — encodes fault network topology into structural sequence
# ---------------------------------------------------------------------------

class GeologicalFaultJEPA(nn.Module):
    """
    JEPA encoder for geological fault network topology (structural state).

    Input  : (1, N_FAULT_SEGS, 6) — per-segment geometric/kinematic parameters
    Output : (1, N_FAULT_SEGS, FAULT_DIM) — per-segment latent fault embeddings

    The encoder learns which structural configurations (locking depth, coupling
    coefficient, geometry) are associated with seismic potential — the "world
    model" representation of the fault system.
    """
    def __init__(self, in_features: int = 6, embed_dim: int = FAULT_DIM):
        super().__init__()
        self.segment_encoder = nn.Sequential(
            nn.Linear(in_features, 128),
            nn.LayerNorm(128),
            nn.GELU(),
            nn.Linear(128, embed_dim),
        )
        self.structural_attention = nn.MultiheadAttention(
            embed_dim=embed_dim, num_heads=4, batch_first=True
        )
        self.norm = nn.LayerNorm(embed_dim)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        z = self.segment_encoder(x)                     # (1, N_FAULT_SEGS, FAULT_DIM)
        z_attn, _ = self.structural_attention(z, z, z)
        return self.norm(z + z_attn)                    # (1, N_FAULT_SEGS, FAULT_DIM)


# ---------------------------------------------------------------------------
# TectonicRiskHead — cross-attention: stress field × fault topology → risk
# ---------------------------------------------------------------------------

class TectonicRiskHead(nn.Module):
    """
    Cross-attention prediction head for tectonic risk localisation.

    This is the Latent Fault Locator applied to the seismic domain.

    stress_field  : (B, STRESS_DIM)          — mean-pooled stress embedding (Query)
    fault_segments: (1, N_FAULT_SEGS, D)    — per-segment fault embeddings (Key, Value)

    The crustal stress state is the Query: it interrogates the fault topology
    to find which fault segments are under the highest stress loading given
    current seismic observations. This is the 'topk coordinate' extraction
    identical in mathematical form to the Materials and Infrastructure domains.

    Returns
    -------
    risk_score    : (B, 1)   — aggregate tectonic risk probability [0, 1]
    attn_weights  : (B, N_FAULT_SEGS)  — per-segment attention weights
    """
    def __init__(self, embed_dim: int = STRESS_DIM):
        super().__init__()
        self.query_proj = nn.Linear(embed_dim, embed_dim)
        self.key_proj   = nn.Linear(embed_dim, embed_dim)
        self.value_proj = nn.Linear(embed_dim, embed_dim)
        self.risk_head  = nn.Sequential(
            nn.Linear(embed_dim, 64),
            nn.ReLU(),
            nn.Linear(64, 1),
            nn.Sigmoid(),
        )
        self.embed_dim = embed_dim

    def forward(
        self,
        stress_field:   torch.Tensor,   # (B, D)
        fault_segments: torch.Tensor,   # (1, N_FAULT_SEGS, D)
    ):
        B = stress_field.shape[0]
        # Expand fault topology across event batch
        fault_exp = fault_segments.expand(B, -1, -1)     # (B, N_FAULT_SEGS, D)

        Q = self.query_proj(stress_field).unsqueeze(1)   # (B, 1, D)
        K = self.key_proj(fault_exp)                     # (B, N_FAULT_SEGS, D)
        V = self.value_proj(fault_exp)                   # (B, N_FAULT_SEGS, D)

        # Scaled dot-product attention
        scores = torch.bmm(Q, K.transpose(1, 2)) / math.sqrt(self.embed_dim)
        attn   = torch.softmax(scores, dim=-1)           # (B, 1, N_FAULT_SEGS)
        ctx    = torch.bmm(attn, V).squeeze(1)           # (B, D)

        risk_score   = self.risk_head(ctx)               # (B, 1)
        attn_weights = attn.squeeze(1)                   # (B, N_FAULT_SEGS)
        return risk_score, attn_weights

    def topk_fault_segments(
        self,
        attn_weights: torch.Tensor,
        k: int = 3,
    ) -> list:
        """Return the fault segment labels with highest attention weight."""
        top_idx = attn_weights.squeeze().topk(k).indices.tolist()
        return [(FAULT_SEGMENT_LABELS[i], i) for i in top_idx]


