# ---------------------------------------------------------------------------

def build_infrastructure_graph():
    """
    Assembles and returns the Lár infrastructure risk graph.
    """
    incident_node = IncidentReportNode(next_node=None)
    monitor_node  = MonitorLogNode(next_node=None)

    router_node = FailureRiskRouterNode(
        threshold=0.50,
        critical_node=incident_node,
        nominal_node=monitor_node,
    )

    crit_head_node = CriticalNodeHeadNode(
        head=_crit_head,
        k=3,
        next_node=router_node,
    )

    topo_emb_node = TopologyGraphEmbeddingNode(
        jepa=_topo_jepa,
        next_node=crit_head_node,
    )

    load_emb_node = NetworkLoadEmbeddingNode(
        jepa=_load_jepa,
        next_node=topo_emb_node,
    )

    return load_emb_node   # entry point


