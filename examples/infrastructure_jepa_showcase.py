class NetworkLoadEmbeddingNode(BaseNode):
    """
    Encodes raw per-probe traffic telemetry into the latent load state.

    Reads  : state["load_data"]          (B, N_PROBES, 6)
    Writes : state["load_embedding"]     (B, LOAD_DIM)
             state["snapshot_index"]     int
    """
    def __init__(self, jepa: NetworkLoadJEPA, next_node=None):
        self.jepa      = jepa
        self.next_node = next_node

    def execute(self, state: GraphState):
        load_data = state.get("load_data")       # (B, N_PROBES, 6)
        with torch.no_grad():
            z_load = self.jepa.encode_load_state(load_data)   # (B, LOAD_DIM)

        state.set("load_embedding", z_load)
        idx = state.get("snapshot_index", 0)
        print(f"\n[NetworkLoadEmbeddingNode] Snapshot {idx}: "
              f"load state encoded → Z_load shape {list(z_load.shape)}, "
              f"mean={z_load.mean().item():.4f}")
        return self.next_node


class TopologyGraphEmbeddingNode(BaseNode):
    """
    Encodes the network graph topology into the structural node sequence.

    Reads  : state["topo_data"]          (1, N_NODES, 6)
    Writes : state["topo_embedding"]     (1, N_NODES, TOPOLOGY_DIM)
    """
    def __init__(self, jepa: TopologyGraphJEPA, next_node=None):
        self.jepa      = jepa
        self.next_node = next_node

    def execute(self, state: GraphState):
        topo_data = state.get("topo_data")       # (1, N_NODES, 6)
        with torch.no_grad():
            z_topo = self.jepa(topo_data)        # (1, N_NODES, TOPOLOGY_DIM)

        state.set("topo_embedding", z_topo)
        print(f"\n[TopologyGraphEmbeddingNode] Graph topology encoded → "
              f"Z_topo shape {list(z_topo.shape)}, "
              f"mean={z_topo.mean().item():.4f}")
        return self.next_node


class CriticalNodeHeadNode(BaseNode):
    """
    Applies cross-attention to project the network load state against the
    infrastructure topology, identifying the topk critical failure nodes.

    Reads  : state["load_embedding"]     (B, LOAD_DIM)
             state["topo_embedding"]     (1, N_NODES, TOPOLOGY_DIM)
    Writes : state["failure_prob"]       float in [0, 1]
             state["critical_nodes"]     list of (label, node_index) tuples
             state["attn_weights"]       (B, N_NODES)
    """
    def __init__(self, head: CriticalNodeHead, k: int = 3, next_node=None):
        self.head      = head
        self.k         = k
        self.next_node = next_node

    def execute(self, state: GraphState):
        z_load = state.get("load_embedding")     # (B, LOAD_DIM)
        z_topo = state.get("topo_embedding")     # (1, N_NODES, TOPOLOGY_DIM)

        with torch.no_grad():
            failure_prob, attn_weights = self.head(z_load, z_topo)

        prob_val       = failure_prob.mean().item()
        critical_nodes = self.head.topk_critical_nodes(attn_weights, k=self.k)

        state.set("failure_prob",    prob_val)
        state.set("critical_nodes",  critical_nodes)
        state.set("attn_weights",    attn_weights)

        print(f"\n[CriticalNodeHeadNode]  failure probability = {prob_val:.4f}")
        print(f"  topk critical nodes (k={self.k}):")
        for label, idx in critical_nodes:
            w = attn_weights.mean(0)[idx].item()
            print(f"    [{idx:>2}] {label:<45} attn={w:.4f}")
        return self.next_node


class FailureRiskRouterNode(BaseNode):
    """
    Routes on cascade failure probability.

    CRITICAL (prob >= threshold) → critical_node
    NOMINAL                      → nominal_node
    """
    def __init__(
        self,
        threshold: float = 0.50,
        critical_node=None,
        nominal_node=None,
    ):
        self.threshold     = threshold
        self.critical_node = critical_node
        self.nominal_node  = nominal_node

    def execute(self, state: GraphState):
        prob = state.get("failure_prob", 0.0)
        tier = "CRITICAL" if prob >= self.threshold else "NOMINAL"
        state.set("risk_tier", tier)
        print(f"\n[FailureRiskRouterNode]  prob={prob:.4f}  threshold={self.threshold}  → {tier}")
        return self.critical_node if prob >= self.threshold else self.nominal_node


class IncidentReportNode(BaseNode):
    """
    Generates a structured infrastructure incident report and escalation record.
    """
    def __init__(self, next_node=None):
        self.next_node = next_node

    def execute(self, state: GraphState):
        failure_prob   = state.get("failure_prob", 0.0)
        critical_nodes = state.get("critical_nodes", [])
        snapshot_idx   = state.get("snapshot_index", 0)

        report = {
            "snapshot_index":   snapshot_idx,
            "risk_tier":        "CRITICAL",
            "failure_prob":     round(failure_prob, 4),
            "critical_nodes": [
                {"label": label, "node_id": idx}
                for label, idx in critical_nodes
            ],
            "recommendation":   "Escalate to NOC. Initiate failover on identified nodes. "
                                 "Increase monitoring frequency. Review capacity on flagged paths.",
        }
        state.set("incident_report", report)

        print("\n" + "=" * 60)
        print("  INFRASTRUCTURE INCIDENT REPORT — CRITICAL")
        print("=" * 60)
        print(f"  Snapshot:         {snapshot_idx}")
        print(f"  Failure Prob:     {failure_prob:.4f}")
        print(f"  Critical Nodes:")
        for node in report["critical_nodes"]:
            print(f"    • [{node['node_id']:>2}] {node['label']}")
        print(f"  Recommendation:   {report['recommendation']}")
        print("=" * 60)
        return self.next_node


class MonitorLogNode(BaseNode):
    """Logs a nominal-risk telemetry snapshot for background monitoring."""
    def __init__(self, next_node=None):
        self.next_node = next_node

    def execute(self, state: GraphState):
        prob = state.get("failure_prob", 0.0)
        idx  = state.get("snapshot_index", 0)
        print(f"\n[MonitorLogNode] Snapshot {idx}: prob={prob:.4f} — nominal. Logged for trending.")
        state.set("incident_report", {"snapshot_index": idx, "risk_tier": "NOMINAL", "failure_prob": round(prob, 4)})
        return self.next_node


