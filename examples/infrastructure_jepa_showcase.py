# ---------------------------------------------------------------------------
# NetworkLoadJEPA — encodes live traffic observations into latent load state
# ---------------------------------------------------------------------------

class NetworkLoadJEPA(nn.Module):
    """
    JEPA encoder for the network traffic load field (environmental state).

    Input  : (B, N_PROBES, 6) — per-probe telemetry feature vectors
    Output : (B, LOAD_DIM)    — mean-pooled latent load embedding

    The encoder learns which combinations of probe observations (throughput,
    latency, packet loss) are predictive of the underlying network stress
    state — the "world model" representation of current traffic conditions.
    Pooled to a single vector: this is the Query in the cross-attention.
    """
    def __init__(self, in_features: int = 6, embed_dim: int = LOAD_DIM):
        super().__init__()
        self.probe_encoder = nn.Sequential(
            nn.Linear(in_features, 128),
            nn.LayerNorm(128),
            nn.GELU(),
            nn.Linear(128, embed_dim),
        )
        self.probe_attention = nn.MultiheadAttention(
            embed_dim=embed_dim, num_heads=4, batch_first=True
        )
        self.norm = nn.LayerNorm(embed_dim)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        z = self.probe_encoder(x)               # (B, N_PROBES, LOAD_DIM)
        z_attn, _ = self.probe_attention(z, z, z)
        return self.norm(z + z_attn)            # (B, N_PROBES, LOAD_DIM)

    def encode_load_state(self, x: torch.Tensor) -> torch.Tensor:
        """Returns mean-pooled load embedding: (B, LOAD_DIM)."""
        probe_embs = self.forward(x)            # (B, N_PROBES, LOAD_DIM)
        return probe_embs.mean(dim=1)           # (B, LOAD_DIM)


# ---------------------------------------------------------------------------
# TopologyGraphJEPA — encodes server graph topology into structural sequence
# ---------------------------------------------------------------------------

class TopologyGraphJEPA(nn.Module):
    """
    JEPA encoder for the network graph topology (structural state).

    Input  : (1, N_NODES, 6)          — per-node centrality / load parameters
    Output : (1, N_NODES, TOPOLOGY_DIM) — per-node latent topology embeddings

    The encoder learns which structural configurations (high betweenness,
    eigenvector centrality, degree) are associated with failure propagation
    risk — the "world model" representation of the network's vulnerability
    landscape. Kept as a positional sequence: these are the Keys and Values
    in the cross-attention.
    """
    def __init__(self, in_features: int = 6, embed_dim: int = TOPOLOGY_DIM):
        super().__init__()
        self.node_encoder = nn.Sequential(
            nn.Linear(in_features, 128),
            nn.LayerNorm(128),
            nn.GELU(),
            nn.Linear(128, embed_dim),
        )
        self.graph_attention = nn.MultiheadAttention(
            embed_dim=embed_dim, num_heads=4, batch_first=True
        )
        self.norm = nn.LayerNorm(embed_dim)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        z = self.node_encoder(x)                      # (1, N_NODES, TOPOLOGY_DIM)
        z_attn, _ = self.graph_attention(z, z, z)
        return self.norm(z + z_attn)                  # (1, N_NODES, TOPOLOGY_DIM)


# ---------------------------------------------------------------------------
# CriticalNodeHead — cross-attention: load state × topology → failure risk
# ---------------------------------------------------------------------------

class CriticalNodeHead(nn.Module):
    """
    Cross-attention prediction head for critical node localisation.

    This is the Latent Fault Locator applied to the network infrastructure domain.

    load_state    : (B, LOAD_DIM)         — pooled load embedding (Query)
    topo_nodes    : (1, N_NODES, D)       — per-node topology embeddings (Key, Value)

    The network load state is the Query: given the current traffic and stress
    conditions observed across all monitoring probes, which specific server
    or router nodes are most likely to cause a cascading failure?

    This is mathematically identical to:
      Drug-JEPA     : RNA disease state queries which DNA positions are kill switches
      Materials-JEPA: Electrochemical state queries which crystal sites are unstable
      Seismic-JEPA  : Crustal stress field queries which fault segments carry risk

    Returns
    -------
    failure_prob  : (B, 1)       — probability of cascade failure event [0, 1]
    attn_weights  : (B, N_NODES) — per-node attention weights (criticality scores)
    """
    def __init__(self, embed_dim: int = LOAD_DIM):
        super().__init__()
        self.query_proj = nn.Linear(embed_dim, embed_dim)
        self.key_proj   = nn.Linear(embed_dim, embed_dim)
        self.value_proj = nn.Linear(embed_dim, embed_dim)
        self.failure_head = nn.Sequential(
            nn.Linear(embed_dim, 64),
            nn.ReLU(),
            nn.Linear(64, 1),
            nn.Sigmoid(),
        )
        self.embed_dim = embed_dim

    def forward(
        self,
        load_state : torch.Tensor,   # (B, D)
        topo_nodes : torch.Tensor,   # (1, N_NODES, D)
    ):
        B = load_state.shape[0]
        topo_exp = topo_nodes.expand(B, -1, -1)          # (B, N_NODES, D)

        Q = self.query_proj(load_state).unsqueeze(1)     # (B, 1, D)
        K = self.key_proj(topo_exp)                      # (B, N_NODES, D)
        V = self.value_proj(topo_exp)                    # (B, N_NODES, D)

        scores = torch.bmm(Q, K.transpose(1, 2)) / math.sqrt(self.embed_dim)
        attn   = torch.softmax(scores, dim=-1)           # (B, 1, N_NODES)
        ctx    = torch.bmm(attn, V).squeeze(1)           # (B, D)

        failure_prob = self.failure_head(ctx)            # (B, 1)
        attn_weights = attn.squeeze(1)                   # (B, N_NODES)
        return failure_prob, attn_weights

    def topk_critical_nodes(
        self,
        attn_weights: torch.Tensor,
        k: int = 3,
    ) -> list:
        """Return the node labels with the highest attention weight."""
        top_idx = attn_weights.squeeze().topk(k).indices.tolist()
        return [(NODE_LABELS[i], i) for i in top_idx]


